"""
hooks.py —— "空槽"机制（整个项目最核心的设计）

说白了：每个空槽就是一个列表，里面装的是函数。
- 插件写好一个函数，用 append 放进对应的槽里
- 引擎在固定的时机，把槽里的函数挨个执行一遍

以后想加新功能，只需要往 plugins/ 里扔一个文件，
在那里 append 一下，主流程一行都不用改。
"""

# 空槽 1：调模型之前执行。
# 插件可以在这里修改 ctx["messages"]，比如：
#   注入知识（RAG）、截断过长的历史、插入系统提示词
before_llm = []

# 空槽 2：模型回答之后执行。
# 插件可以在这里修改 ctx["reply"]，比如：
#   过滤敏感词、打印日志、统计字数
after_llm = []

# 以后想加新空槽？在下面再加一个列表就行，例如：
# on_request = []      # 收到用户消息时
# on_response = []     # 返回给浏览器之前


def run(slot, ctx):
    """把某个空槽里的函数依次执行一遍。

    参数：
      slot —— 哪个槽（比如 before_llm）
      ctx  —— 上下文字典，本项目的"共享数据袋"，结构见 engine.py

    注意：函数是"原地修改"ctx 的，不需要有返回值。
    """
    for fn in slot:
        fn(ctx)
    return ctx
